import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const start=app.indexOf('function datedOdometerReadings(');
const end=app.indexOf('function migrateData(',start);
assert(start>0&&end>start,'里程日期資料升級函式必須存在');
const functions=new Function('isLexusVehicleName','state','vehicleById',`${app.slice(start,end)};return {reconcileDatedVehicleOdometers,datedOdometerReadings};`);
const historicalFuel={id:'fuel-9-7',vehicleId:'v2',date:'2026-09-07',odometer:321782,liters:40,amount:1300};
const invoice={id:'lex-maint-20261015-AI151015004',vehicleId:'v2',date:'2026-10-15',odometer:322082,workOrder:'AI151015004',notes:'2026/10/18系統畫面顯示車輛最新里程321,782 km，比本工單少300 km；兩筆里程需重新核對，勿擅改原始單據。'};
const reminder={id:'lex-reminder',sourceId:invoice.id,notes:'依權威汽車工單 AI151015004；里程時序待核對（2026/10/18螢幕值321,782 km，比10/15原單里程322,082 km低）。'};
const fixture={vehicles:[{id:'v2',name:'LEXUS ES300',odometer:321782}],fuel:[historicalFuel],maintenance:[invoice],reminders:[reminder],mileageLogs:[]};
const data=structuredClone(fixture);
const {reconcileDatedVehicleOdometers,datedOdometerReadings}=functions(s=>s.toUpperCase().includes('LEXUS'),data,id=>data.vehicles.find(v=>v.id===id));
reconcileDatedVehicleOdometers(data);
assert.equal(data.vehicles[0].odometer,322082,'主檔應為最新已知有效里程');
assert.equal(data.vehicles[0].odometerDate,'2026-10-15','必須保有量測日，不能自動標今天');
assert.equal(datedOdometerReadings(data,'v2')[0].date,'2026-09-07');
assert.equal(datedOdometerReadings(data,'v2')[1].date,'2026-10-15');
assert(!data.maintenance[0].notes.includes('2026/10/18系統畫面'),'錯誤系統自動警告需移除');
assert(!data.reminders[0].notes.includes('時序待核對'),'提醒不可保留舊的誤判文字');
reconcileDatedVehicleOdometers(data);
assert.equal(data.vehicles[0].odometer,322082,'多次升級不重複或扭曲里程');
const newFuel={...historicalFuel,id:'fuel-10-18',date:'2026-10-18',odometer:322450};
data.fuel.push(newFuel);
reconcileDatedVehicleOdometers(data);
assert.equal(data.vehicles[0].odometer,322450);
assert.equal(data.vehicles[0].odometerDate,'2026-10-18');
const futureEarlier={...fixture,vehicles:[{id:'v2',name:'LEXUS ES300',odometer:321782}],fuel:[],maintenance:[invoice],reminders:[],mileageLogs:[]};
const fns=functions(s=>s.toUpperCase().includes('LEXUS'),futureEarlier,()=>futureEarlier.vehicles[0]);
fns.reconcileDatedVehicleOdometers(futureEarlier);
assert.equal(futureEarlier.vehicles[0].odometer,322082,'內建舊版本即使缺9/7燃油細節，也不可錯把322082當異常');
assert.equal(futureEarlier.vehicles[0].odometerDate,'2026-10-15');
const unknown={...fixture,vehicles:[{id:'v2',name:'LEXUS ES300',odometer:329000}],fuel:[historicalFuel],maintenance:[invoice],reminders:[],mileageLogs:[]};
functions(s=>s.toUpperCase().includes('LEXUS'),unknown,()=>unknown.vehicles[0]).reconcileDatedVehicleOdometers(unknown);
assert.equal(unknown.vehicles[0].odometer,329000,'不可擅自覆蓋使用者未註明日期的新里程');
assert.equal(unknown.vehicles[0].odometerDate,'','未知量測日期不能偽裝成今天');
console.log('PASS: 9/7 321782 → 10/15 322082，最新已知里程與日期更新正確');
console.log('PASS: 自動刪除舊版虛假「10/18里程倒退」警告與提醒文字');
console.log('PASS: 新燃油更新日期、重複升級冪等、無原始9/7燃油時仍可修正主檔');
